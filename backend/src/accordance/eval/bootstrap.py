"""Bootstrap a candidate ground-truth YAML from a completed run's findings.

    python -m accordance.eval.bootstrap <run_id> [--out PATH] [--blank-status]

Pre-fills a GroundTruth-schema YAML from the pipeline's OWN findings, annotated
with the judge's notes/evidence so a human can VERIFY each call against the PDF.
This is a typing time-saver, NOT ground truth. Use --blank-status to leave every
status unfilled (no anchoring) — the file then fails validation until filled.
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import re
import sys
from pathlib import Path

from accordance.config import Settings, get_settings
from accordance.db import connect_direct, ensure_embedding_dim, ensure_schema
from accordance.indexer.embedder import embedding_dim

_FILL = "FILL_ME"


def _slugify(filename: str) -> str:
    stem = Path(filename).stem.lower()
    slug = re.sub(r"[^a-z0-9]+", "-", stem).strip("-")
    return slug or "report"


def _esc(s: str | None) -> str:
    """Collapse to one line, drop control chars, escape for a double-quoted YAML scalar."""
    s = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", s or "")
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    return re.sub(r"\s+", " ", s).strip()


def _open_conn(settings: Settings):
    conn = connect_direct(settings)
    ensure_schema(conn)
    ensure_embedding_dim(conn, dim=embedding_dim(settings.embedding_model))
    return conn


def render_ground_truth(
    run_row: dict,
    findings: list[dict],
    *,
    blank_status: bool,
) -> str:
    """Render a GroundTruth YAML (with comments) from run + findings rows.

    `run_row` and each `findings` item are mapping-like (psycopg dict-row or dict)
    exposing keys: run_row[id|pdf_filename|pdf_sha256]; finding[disclosure_id|
    status|note|evidence_excerpt|evidence_page|elements_json].
    """
    today = _dt.date.today().isoformat()
    L: list[str] = [
        "# AUTO-GENERATED by accordance.eval.bootstrap — NOT ground truth.",
        "# These are the PIPELINE'S OWN guesses. Verify EVERY status against the",
        "# PDF before trusting this for eval. Watch especially:",
        "#   - 'missing'  -> may be a retrieval miss (data IS in the report)",
        "#   - 'covered'  -> may be an over-confident / hallucinated verdict",
        f"# Source run: {run_row['id']}",
        "",
        f"report_id: {_slugify(run_row['pdf_filename'])}",
        f'pdf_filename: "{_esc(run_row["pdf_filename"])}"',
    ]
    sha = run_row["pdf_sha256"]
    L.append(f'pdf_sha256: "{_esc(sha)}"' if sha else "pdf_sha256:")
    L.append("pdf_path:")
    L.append('labeler: "BOOTSTRAP — VERIFY AGAINST PDF"')
    L.append(f"labeled_at: {today}")
    L.append("disclosures:")

    has_disclosure = False
    for f in findings:
        did = f["disclosure_id"]
        status = f["status"]
        if status == "error":
            L.append(f"  # {did}: run errored — label this disclosure manually.")
            continue
        has_disclosure = True
        L.append(f'  - id: "{did}"')
        if blank_status:
            L.append(f"    expected_status: {_FILL}   # judge said: {status}")
        else:
            L.append(f"    expected_status: {status}")
        if f["evidence_page"] is not None:
            L.append(f"    expected_evidence_page: {f['evidence_page']}")
        note = _esc(f["note"])
        if note:
            L.append(f'    notes: "{note}"')
        excerpt = _esc(f["evidence_excerpt"])
        if excerpt:
            L.append(f"    # judge evidence: {excerpt}")
        elements = json.loads(f["elements_json"] or "[]")
        if elements:
            L.append("    elements:")
            for e in elements:
                L.append(f'      - id: "{e["id"]}"')
                if blank_status:
                    L.append(f"        expected_status: {_FILL}   # judge said: {e['status']}")
                else:
                    L.append(f"        expected_status: {e['status']}")
                if e.get("page") is not None:
                    L.append(f"        expected_page: {e['page']}")
        L.append("")
    if not has_disclosure:
        # All findings were errors — emit an explicit empty list so yaml.safe_load
        # returns [] rather than None for the disclosures key.
        L.append("  []")
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m accordance.eval.bootstrap")
    p.add_argument("run_id")
    p.add_argument("--out", type=Path, default=None)
    p.add_argument("--blank-status", action="store_true")
    args = p.parse_args(argv)

    settings = get_settings()
    conn = _open_conn(settings)
    try:
        run_row = conn.execute("SELECT * FROM runs WHERE id=%s", (args.run_id,)).fetchone()
        if not run_row:
            print(f"Run not found: {args.run_id}", file=sys.stderr)
            return 1
        findings = conn.execute(
            "SELECT * FROM findings WHERE run_id=%s ORDER BY disclosure_id",
            (args.run_id,),
        ).fetchall()
        if not findings:
            print(f"Run {args.run_id} has no findings.", file=sys.stderr)
            return 1
        text = render_ground_truth(run_row, findings, blank_status=args.blank_status)
        slug = _slugify(run_row["pdf_filename"])
    finally:
        conn.close()

    out = args.out or (Path("eval/ground_truth") / f"{slug}.yaml")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"Wrote {out} ({len(findings)} findings). VERIFY against the PDF before eval.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
